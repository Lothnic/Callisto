// Run with node tests/extension-content.mjs; uses the mini workspace's Playwright.
// This exercises DOM behavior in disposable Chromium, not Firefox extension APIs.
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
const require = createRequire(import.meta.url);
const { chromium } = require('../../mini/node_modules/playwright-core');
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/snap/bin/chromium', headless: true, args: ['--no-sandbox'] });
try {
  const page = await browser.newPage();
  await page.setContent('<label for="email">Email</label><input id="email"><label for="password">Password</label><input id="password" type="password" value="secret"><button id="send">Send</button><button id="disabled" disabled>Disabled</button><script>window.clicked=0;send.onclick=()=>window.clicked++</script>');
  await page.evaluate(() => { window.browser = {runtime:{onMessage:{addListener(fn){ window.callistoListener = fn; }}}}; });
  await page.addScriptTag({ path: fileURLToPath(new URL('../extension/content.js', import.meta.url)) });
  const invoke = (message) => page.evaluate(m => window.callistoListener(m), message);
  const snapshot = await invoke({type:'action', method:'snapshot'});
  assert(!snapshot.value.text.includes('secret'));
  assert(snapshot.value.text.includes('[REDACTED]'));
  const ref = label => snapshot.value.text.split('\n').find(line => line.includes(`"${label}"`)).match(/\[(ax-\d+)\]/)[1];
  await page.evaluate(() => {
    window.inputEvents = [];
    for (const type of ['input', 'click']) document.addEventListener(type, event => window.inputEvents.push({type, trusted:event.isTrusted}), true);
  });
  assert.deepEqual(await invoke({type:'action',method:'fill',ref:ref('Email'),value:'hello@example.com'}), {value:{completed:true}});
  assert.equal(await page.locator('#email').inputValue(), 'hello@example.com');
  await page.locator('#email').evaluate(el=>el.addEventListener('keydown',event=>{window.keySeen={key:event.key,ctrl:event.ctrlKey,trusted:event.isTrusted};}));
  const pressed=await invoke({type:'action',method:'page',value:JSON.stringify({action:'press',key:'Control+a'})});
  assert.equal(pressed.value.defaultBrowserBehavior,false);
  assert.deepEqual(await page.evaluate(()=>window.keySeen),{key:'a',ctrl:true,trusted:false});
  assert.deepEqual(await invoke({type:'action',method:'click',ref:ref('Send')}), {value:{completed:true}});
  assert.equal(await page.evaluate(() => window.clicked), 1);
  assert.deepEqual(await page.evaluate(() => window.inputEvents), [{type:'input',trusted:false},{type:'click',trusted:false}]);
  assert.match((await invoke({type:'action',method:'click',ref:ref('Disabled')})).error, /disabled/i);
  await page.evaluate(()=>{
    document.title='Fixture';
    document.body.insertAdjacentHTML('beforeend','<form id="form"><label for="query">Search</label><input id="query" role="combobox" name="q" required><button type="submit">Find</button></form>');
    window.submitted=0;document.querySelector('#form').onsubmit=e=>{e.preventDefault();window.submitted++};
  });
  await invoke({type:'ping'});
  assert.equal(await page.title(),'[Callisto] Fixture');
  await page.evaluate(()=>{document.title='Site updated'});
  await page.waitForFunction(()=>document.title==='[Callisto] Site updated');
  const formSnapshot=await invoke({type:'action',method:'snapshot'});
  const queryRef=formSnapshot.value.text.split('\n').find(line=>line.includes('combobox "Search"')).match(/\[(ax-\d+)\]/)[1];
  assert.equal((await invoke({type:'action',method:'submit',ref:queryRef})).error,'Form validation failed; complete the required fields before submitting.');
  await invoke({type:'action',method:'fill',ref:queryRef,value:'browser research'});
  const filled=await invoke({type:'action',method:'snapshot'});
  assert(filled.value.text.includes('combobox "Search" =browser research'));
  assert.equal((await invoke({type:'action',method:'submit',ref:queryRef})).value.completed,true);
  assert.equal(await page.evaluate(()=>window.submitted),1);
  await page.evaluate(()=>{
    const host=document.createElement('div'); document.body.append(host);
    host.attachShadow({mode:'open'}).innerHTML='<button>Shadow action</button>';
    host.shadowRoot.querySelector('button').onclick=()=>window.shadowClicked=true;
  });
  const shadowSnapshot=await invoke({type:'action',method:'snapshot'});
  const shadowRef=shadowSnapshot.value.text.split('\n').find(line=>line.includes('"Shadow action"')).match(/\[(ax-\d+)\]/)[1];
  assert.equal((await invoke({type:'action',method:'click',ref:shadowRef})).value.completed,true);
  assert.equal(await page.evaluate(()=>window.shadowClicked),true);
  await page.evaluate(()=>{const host=[...document.querySelectorAll('div')].find(el=>el.shadowRoot);host.inert=true;});
  assert.match((await invoke({type:'action',method:'click',ref:shadowRef})).error,/not visible/);
  await page.evaluate(()=>{[...document.querySelectorAll('div')].find(el=>el.shadowRoot).inert=false;});
  await page.evaluate(()=>{
    document.body.insertAdjacentHTML('afterbegin','<div id="clipped" style="height:50px;overflow:auto"><div style="height:100px"></div><button onclick="window.clippedClicked=true">Clipped control</button></div>');
  });
  const clippedSnapshot=await invoke({type:'action',method:'snapshot'});
  const clippedRef=clippedSnapshot.value.text.split('\n').find(line=>line.includes('"Clipped control"')).match(/\[(ax-\d+)\]/)[1];
  assert.equal((await invoke({type:'action',method:'click',ref:clippedRef})).value?.completed,true);
  assert.equal(await page.evaluate(()=>window.clippedClicked),true);
  await page.evaluate(()=>{
    document.body.insertAdjacentHTML('beforeend','<section id="observed"><p>Invoice total: 42 dollars</p><button>Open invoice</button></section>');
    const host=document.createElement('div');host.id='observed-shadow';document.body.append(host);host.attachShadow({mode:'open'}).innerHTML='<p>Shadow invoice: 99 dollars</p><button>Shadow invoice</button><div class="shadow-row">S1</div>';
  });
  const observe=options=>invoke({type:'action',method:'snapshot',value:JSON.stringify(options)});
  const observed=await observe({selector:'#observed',max_chars:1000});
  assert(observed.value.text.includes('Invoice total: 42 dollars'));
  assert(observed.value.text.includes('button "Open invoice"'));
  assert(!observed.value.text.includes('Clipped control'));
  assert(!(await observe({selector:'#observed',include_text:false})).value.text.includes('42 dollars'));
  const queried=await observe({selector:'#observed-shadow',query:'99 dollars'});
  assert(queried.value.text.includes('Shadow invoice: 99 dollars'));
  const shadowRows=await invoke({type:'action',method:'page',value:JSON.stringify({action:'extract',spec:{selector:'.shadow-row',fields:{value:{}}}})});
  assert.deepEqual(shadowRows.value.rows,[{value:'S1'}]);
  assert.match((await observe({selector:'[['})).error,/Invalid observation selector/);
  assert.match((await observe({selector:'button'})).error,/exactly one/);
  await page.evaluate(()=>document.body.insertAdjacentHTML('beforeend','<input type="file" aria-label="Attachment">'));
  const uploadSnapshot=await invoke({type:'action',method:'snapshot'});
  const uploadRef=uploadSnapshot.value.text.split('\n').find(line=>line.includes('"Attachment"')).match(/\[(ax-\d+)\]/)[1];
  const uploaded=await invoke({type:'action',method:'page',value:JSON.stringify({action:'upload',ref:uploadRef,files:[{name:'fixture.bin',data:'AAH/'}]})});
  assert.equal(uploaded.value.completed,true);
  assert.deepEqual(await page.evaluate(async()=>[...new Uint8Array(await document.querySelector('input[type=file]').files[0].arrayBuffer())]),[0,1,255]);
  const human=invoke({type:'handoff',prompt:'Complete the fixture step.',timeout_ms:5000});
  await page.getByText('Callisto needs your help',{exact:true}).waitFor();
  assert.match((await invoke({type:'action',method:'click',ref:shadowRef})).error,/handoff is pending/);
  await page.getByRole('button',{name:'Continue with agent'}).click();
  assert.equal((await human).value.confirmed,true);
  await page.evaluate(()=>{
    const frame=document.createElement('iframe');frame.id='fixture-frame';frame.srcdoc='<button onclick="window.wasClicked=true">Frame action</button>';const wrapper=document.createElement('div');wrapper.append(frame);document.body.prepend(wrapper);
  });
  await page.frameLocator('#fixture-frame').getByRole('button',{name:'Frame action'}).waitFor();
  const child=page.frames().find(frame=>frame!==page.mainFrame());
  await child.evaluate(()=>{window.browser={runtime:{onMessage:{addListener(fn){window.callistoListener=fn;}}}};});
  await child.addScriptTag({path:fileURLToPath(new URL('../extension/content.js',import.meta.url))});
  const frameInvoke=message=>child.evaluate(m=>window.callistoListener(m),message);
  const frameSnapshot=await frameInvoke({type:'action',method:'snapshot'});
  const frameRef=frameSnapshot.value.text.match(/\[(ax-\d+)\]/)[1];
  assert.equal((await frameInvoke({type:'action',method:'click',ref:frameRef})).value.completed,true);
  await page.evaluate(()=>{
    const cover=document.createElement('div');cover.id='frame-cover';const r=document.querySelector('#fixture-frame').getBoundingClientRect();
    cover.style.cssText=`position:fixed;left:${r.left}px;top:${r.top}px;width:${r.width}px;height:${r.height}px;background:red;z-index:1000`;document.body.append(cover);
  });
  assert.match((await frameInvoke({type:'action',method:'click',ref:frameRef})).error,/Frame is covered/);
  await page.locator('#frame-cover').evaluate(el=>el.remove());
  await page.locator('#fixture-frame').evaluate(el=>{el.parentElement.style.transform='scale(1.1)';});
  assert.match((await frameInvoke({type:'action',method:'click',ref:frameRef})).error,/Transformed frame/);
  await page.evaluate(()=>{
    document.body.insertAdjacentHTML('beforeend','<table id="extract-grid"><tbody><tr><td>Alpha</td><td>3</td></tr><tr><td>Beta</td><td>5</td></tr></tbody></table>');
  });
  const extracted=await invoke({type:'action',method:'page',value:JSON.stringify({action:'extract',spec:{selector:'#extract-grid tbody tr',fields:{name:'td:nth-child(1)',total:{selector:'td:nth-child(2)',type:'number'}}}})});
  assert.deepEqual(extracted.value,{url:'about:blank',title:'Site updated',rows:[{name:'Alpha',total:3},{name:'Beta',total:5}],has_next:false,omitted:false});
  const limited=await invoke({type:'action',method:'page',value:JSON.stringify({action:'extract',spec:{selector:'#extract-grid tbody tr',fields:{name:'td:nth-child(1)'},limit:1,include_text:true}})});
  assert.equal(limited.value.rows.length,1);
  assert.equal(limited.value.omitted,true);
  assert.match(limited.value.rows[0]._text,/^Alpha 3$/);
  assert.match((await invoke({type:'action',method:'page',value:JSON.stringify({action:'extract',spec:{selector:'[[',fields:{name:'td'}}})})).error,/Invalid row selector/);
  // A short animation must settle within one action, without replaying a click.
  await page.evaluate(()=>{
    document.body.insertAdjacentHTML('afterbegin','<button id="moving" style="position:relative">Moving action</button>');
    window.movingClicks=0;moving.onclick=()=>window.movingClicks++;
    const start=performance.now();
    window.motion=setInterval(()=>{moving.style.left=`${(performance.now()-start)/2}px`;},10);
    setTimeout(()=>clearInterval(window.motion),220);
  });
  const movingSnapshot=await invoke({type:'action',method:'snapshot'});
  const movingRef=movingSnapshot.value.text.split('\n').find(line=>line.includes('"Moving action"')).match(/\[(ax-\d+)\]/)[1];
  assert.equal((await invoke({type:'action',method:'click',ref:movingRef})).value?.completed,true);
  assert.equal(await page.evaluate(()=>window.movingClicks),1);
  await page.evaluate(()=>{
    document.body.insertAdjacentHTML('afterbegin','<button id="covered">Covered action</button><div id="cover" style="position:fixed;inset:0;background:white;z-index:9999"></div>');
    window.coveredClicks=0;covered.onclick=()=>window.coveredClicks++;
    setTimeout(()=>document.querySelector('#cover').remove(),120);
  });
  const coveredSnapshot=await invoke({type:'action',method:'snapshot'});
  const coveredRef=coveredSnapshot.value.text.split('\n').find(line=>line.includes('"Covered action"')).match(/\[(ax-\d+)\]/)[1];
  assert.equal((await invoke({type:'action',method:'click',ref:coveredRef})).value?.completed,true);
  assert.equal(await page.evaluate(()=>window.coveredClicks),1);
  await page.evaluate(()=>setTimeout(()=>document.body.insertAdjacentHTML('beforeend','<div id="async-result">'+'ready '.repeat(60)+'</div>'),100));
  const wait=spec=>invoke({type:'action',method:'page',value:JSON.stringify({action:'wait_for',...spec})});
  assert.equal((await wait({selector:'#async-result',state:'visible',timeout_ms:1000})).value?.matched,true);
  assert.equal((await wait({text:'ready '.repeat(60).trim(),timeout_ms:1000})).value?.matched,true);
  assert.equal((await wait({selector:'#missing',state:'hidden',timeout_ms:1000})).value?.matched,true);
  assert.match((await wait({selector:'[[',timeout_ms:100})).error,/Invalid wait selector/);
  assert.match((await wait({selector:'#missing',timeout_ms:100})).error,/timed out/);
  await page.evaluate(()=>setTimeout(()=>document.querySelector('#async-result').remove(),50));
  assert.equal((await wait({selector:'#async-result',state:'detached',timeout_ms:1000})).value?.matched,true);
  await page.evaluate(()=>{
    document.body.insertAdjacentHTML('afterbegin','<div id="persistent-cover" style="position:fixed;inset:0;background:white;z-index:9999"></div>');
  });
  const bounded=await invoke({type:'action',method:'click',ref:coveredRef,deadline:Date.now()+150});
  assert.match(bounded.error,/deadline|covered/);
  assert.equal(await page.evaluate(()=>window.coveredClicks),1);
  await page.locator('#persistent-cover').evaluate(el=>el.remove());
  // Disabled/read-only state must be checked again after waiting for stability.
  await page.evaluate(()=>{
    covered.disabled=false;
    requestAnimationFrame(()=>{covered.disabled=true;});
  });
  assert.match((await invoke({type:'action',method:'click',ref:coveredRef})).error,/disabled/);
  await page.evaluate(()=>{covered.disabled=false;});
  const pendingWait=wait({selector:'#never-arrives',timeout_ms:5000});
  await page.waitForTimeout(60);
  await invoke({type:'revoke'});
  await invoke({type:'ping'});
  assert.match((await pendingWait).error,/Sharing stopped/);
  await page.evaluate(()=>{
    document.body.innerHTML='<form id="multi"><button name="first">First</button><button name="second">Second</button></form><div class="row">A</div><button id="hidden-next" style="display:none" onclick="document.body.dataset.clicked=1">Next</button>';
    document.querySelector('form').onsubmit=event=>{event.preventDefault();window.submitter=event.submitter.name;};
  });
  const multi=await invoke({type:'action',method:'snapshot'});
  const second=multi.value.text.split('\n').find(line=>line.includes('"Second"')).match(/\[(ax-\d+)\]/)[1];
  assert.equal((await invoke({type:'action',method:'submit',ref:second})).value.completed,true);
  assert.equal(await page.evaluate(()=>window.submitter),'second');
  const hidden=await invoke({type:'action',method:'page',value:JSON.stringify({action:'click_next',selector:'#hidden-next'})});
  assert.match(hidden.error,/not visible/);
  assert.equal(await page.evaluate(()=>document.body.dataset.clicked),undefined);
  await page.evaluate(()=>{
    document.body.innerHTML=Array.from({length:450},(_,i)=>`<button onclick="window.lastClicked=${i}">Control ${i}</button>`).join('');
  });
  const compact=await invoke({type:'action',method:'snapshot',value:JSON.stringify({max_chars:1000})});
  assert(compact.value.truncated && compact.value.text.length<=1000);
  assert(compact.value.text.endsWith('"'));
  const firstPage=await invoke({type:'action',method:'snapshot',value:JSON.stringify({max_chars:1000})});
  assert(firstPage.value.next_offset>0 && firstPage.value.next_offset<450);
  await page.evaluate(()=>document.body.insertAdjacentHTML('afterbegin','<div id="new-observation">New generic text</div><button>Inserted later</button>'));
  const wrongRevision=await invoke({type:'action',method:'snapshot',value:JSON.stringify({offset:firstPage.value.next_offset,revision:'wrong'})});
  assert.match(wrongRevision.error,/revision/i);
  const lastPage=await invoke({type:'action',method:'snapshot',value:JSON.stringify({offset:firstPage.value.next_offset,max_chars:30000})});
  assert.equal(lastPage.value.revision,firstPage.value.revision);
  assert.equal(lastPage.value.live_changed,true);
  assert(!lastPage.value.text.includes('Inserted later'));
  assert.equal(lastPage.value.truncated,false);
  assert.equal(lastPage.value.next_offset,null);
  assert.equal(lastPage.value.text.split('\n').length,450-firstPage.value.next_offset);
  assert(lastPage.value.text.includes('"Control 449"'));
  const lastRef=lastPage.value.text.split('\n').at(-1).match(/\[(ax-\d+)\]/)[1];
  await invoke({type:'action',method:'snapshot',value:JSON.stringify({preserve_refs:true})});
  assert.equal((await invoke({type:'action',method:'click',ref:lastRef})).value?.completed,true);
  assert.equal(await page.evaluate(()=>window.lastClicked),449);
  const emptyPage=await invoke({type:'action',method:'snapshot',value:JSON.stringify({offset:450})});
  assert.equal(emptyPage.value.text,'');
  assert.equal(emptyPage.value.truncated,false);
  assert.match((await invoke({type:'action',method:'snapshot',value:JSON.stringify({offset:-1})})).error,/Invalid snapshot/);
  const delta=await invoke({type:'action',method:'snapshot',value:JSON.stringify({diff:true,max_chars:1000})});
  assert.equal(delta.value.diff,true);
  assert(delta.value.text.includes('New generic text'));
  assert(delta.value.text.includes('Inserted later'));
  const unchanged=await invoke({type:'action',method:'snapshot',value:JSON.stringify({diff:true,max_chars:1000})});
  assert.equal(unchanged.value.text,'');
  await page.evaluate(()=>document.body.innerHTML='<div>Repeated text</div><div>Repeated text</div><button id="one">One</button><button id="two">Two</button>');
  const beforeDuplicates=await invoke({type:'action',method:'snapshot'});
  await page.evaluate(()=>document.querySelector('div').remove());
  const duplicateDelta=await invoke({type:'action',method:'snapshot',value:JSON.stringify({diff:true})});
  assert.equal(duplicateDelta.value.base_revision,beforeDuplicates.value.revision);
  assert.equal(duplicateDelta.value.text,'- text "Repeated text"');
  await page.evaluate(()=>document.body.insertBefore(document.querySelector('#two'),document.querySelector('#one')));
  const reordered=await invoke({type:'action',method:'snapshot',value:JSON.stringify({diff:true})});
  assert.equal(reordered.value.order_changed,true);
  assert.equal(reordered.value.text,'');
  await page.evaluate(()=>document.body.innerHTML='<input aria-label="First"><input aria-label="Other">');
  const inputNonce='a'.repeat(64);
  assert((await invoke({type:'action',method:'input_prepare',value:JSON.stringify({action:'fill',role:'textbox',name:'First',nonce:inputNonce})})).value);
  await page.locator('[aria-label="Other"]').focus();
  const focusChanged=await invoke({type:'action',method:'input_validate',value:JSON.stringify({nonce:inputNonce,keyboard:true})});
  assert.match(focusChanged.error,/focus changed/);
  const interrupted=invoke({type:'handoff',prompt:'This step will be revoked.',timeout_ms:5000});
  await page.getByText('This step will be revoked.',{exact:true}).waitFor();
  await invoke({type:'revoke'});
  assert.match((await interrupted).error,/Sharing stopped/);
  assert.equal(await page.title(),'Site updated');
  assert.match((await invoke({type:'action',method:'click',ref:ref('Send')})).error, /sharing stopped/i);
  console.log('DOM bridge checks passed (disposable Chromium).');
} finally { await browser.close(); }
